'use strict';

/**
 * Emit fail-closed Pilot readiness board as JSON + Markdown artifacts.
 * Offline only — never connects to SQL or claims production verification.
 */
const fs = require('node:fs');
const path = require('node:path');
const {buildPilotReadinessBoard} = require('./readiness-board.cjs');
const {buildWorkflowMatrix} = require('./workflow-matrix-builder.cjs');
const {buildPilotWorkflowChecklist} = require('./workflow-checklist.cjs');
const {buildE2eEvidenceMatrix} = require('./e2e-matrix.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const OUT_DIR = path.join(__dirname, 'artifacts');

function ensureOutDir() {
  fs.mkdirSync(OUT_DIR, {recursive: true});
}

function renderMarkdown(board, matrix, checklist, e2e) {
  const lines = [];
  lines.push('# DRVO Pilot Readiness Board (machine-generated)');
  lines.push('');
  lines.push('> **Fail-closed.** `productionVerificationClaimed=false`. Real-data activation **BLOCKED**. ADR-031 posting **BLOCKED**. Cut live import **BLOCKED**. Primary/VPS SQL apply **FORBIDDEN**.');
  lines.push('');
  lines.push('Generated by `tools/pilot/render-board.cjs`. Modular Monolith Tenant/Business/Branch isolation remains mandatory.');
  lines.push('');
  lines.push('## Gate board');
  lines.push('');
  lines.push('| Gate | Status | Evidence class | Evidence |');
  lines.push('| --- | --- | --- | --- |');
  for (const g of board.gates) {
    lines.push(
      `| \`${g.id}\` | **${g.status}** | ${g.evidenceClass} | ${g.evidence.replace(/\|/g, '/')} |`
    );
  }
  lines.push('');
  lines.push('Blocking gate ids: `' + board.blockingGateIds.join('`, `') + '`');
  lines.push('');
  lines.push('## Workflow matrix');
  lines.push('');
  lines.push(matrix.workflow);
  lines.push('');
  lines.push('| Step | Matrix status | Notes |');
  lines.push('| --- | --- | --- |');
  for (const s of matrix.steps) {
    lines.push(`| ${s.title} (\`${s.id}\`) | **${s.status}** | ${s.notes.replace(/\|/g, '/')} |`);
  }
  lines.push('');
  lines.push('## S12/S13 checklist');
  lines.push('');
  lines.push(
    'Covered: `' +
      checklist.summary.s12s13CoveredStepIds.join('`, `') +
      '`. Open/uncovered: `' +
      checklist.summary.openOrUncoveredStepIds.join('`, `') +
      '`.'
  );
  lines.push('');
  lines.push('## E2E evidence matrix (PASS / FAIL / BLOCKED)');
  lines.push('');
  lines.push('| Step | Gate | Evidence command |');
  lines.push('| --- | --- | --- |');
  for (const row of e2e.steps) {
    lines.push(
      `| ${row.title} | **${row.gate}** | \`${row.evidenceCommand.replace(/\|/g, '/')}\` |`
    );
  }
  lines.push('');
  lines.push('## Operator procedure (isolated Pilot DB only)');
  lines.push('');
  lines.push('1. Confirm dedicated Pilot DB name (never Cut/Cashier/AutoResponse/primary VPS).');
  lines.push('2. Backup first; `RESTORE VERIFYONLY`; restore into a **new** recovery DB.');
  lines.push('3. Apply SQL001–034 only on the isolated Pilot DB with restricted migrator; re-read `core.SchemaMigration` checksums.');
  lines.push('4. Bootstrap K5 Owner for the Pilot Tenant/Business/Branch; keep ADR-031 flags OFF.');
  lines.push('5. Run Owner browser E2E for Customer → Booking → Barber → POS Draft → Inventory → Draft Print (NONPOSTING window.print) → Reload.');
  lines.push('6. Draft Print is **READY_IN_REPO** after #151 (NONPOSTING `window.print` only). Fiscal/paid receipt stays **BLOCKED**. Owner Pilot browser proof remains **OPEN**.');
  lines.push('7. Never import live Cut data from this track.');
  lines.push('');
  lines.push('## Local offline commands');
  lines.push('');
  lines.push('```bash');
  lines.push('node --test tests/pilot-readiness.test.cjs');
  lines.push('node tools/pilot/verify.cjs');
  lines.push('node tools/pilot/render-board.cjs');
  lines.push('```');
  lines.push('');
  return lines.join('\n');
}

function writeArtifacts(outDir = OUT_DIR) {
  ensureOutDir();
  const board = buildPilotReadinessBoard();
  const matrix = buildWorkflowMatrix();
  const checklist = buildPilotWorkflowChecklist();
  const e2e = buildE2eEvidenceMatrix();

  const boardJsonPath = path.join(outDir, 'readiness-board.json');
  const boardMdPath = path.join(outDir, 'readiness-board.md');
  const e2eJsonPath = path.join(outDir, 'e2e-evidence-matrix.json');

  fs.writeFileSync(boardJsonPath, JSON.stringify(board, null, 2) + '\n', 'utf8');
  fs.writeFileSync(e2eJsonPath, JSON.stringify(e2e, null, 2) + '\n', 'utf8');
  fs.writeFileSync(
    boardMdPath,
    renderMarkdown(board, matrix, checklist, e2e),
    'utf8'
  );

  return Object.freeze({
    board,
    matrix,
    checklist,
    e2e,
    paths: Object.freeze({
      boardJson: path.relative(ROOT, boardJsonPath).replace(/\\/g, '/'),
      boardMd: path.relative(ROOT, boardMdPath).replace(/\\/g, '/'),
      e2eJson: path.relative(ROOT, e2eJsonPath).replace(/\\/g, '/'),
    }),
  });
}

if (require.main === module) {
  const result = writeArtifacts();
  console.log(
    JSON.stringify(
      {
        ok: true,
        productionVerificationClaimed: false,
        realDataActivation: 'BLOCKED',
        paths: result.paths,
        blockingGateIds: result.board.blockingGateIds,
      },
      null,
      2
    )
  );
}

module.exports = {OUT_DIR, writeArtifacts, renderMarkdown};
